export type MessageKey = keyof typeof messages.en;

export function t(language: Language, key: MessageKey, vars?: Record<string, string | number>): string {
  let message: string = messages[language][key] ?? messages.en[key];
  if (vars) for (const [name, value] of Object.entries(vars)) message = message.replaceAll(`{${name}}`, String(value));
  return message;
}

export function nativeLanguageName(language: Language): string {
  return t(language, language === "en" ? "languageEnglish" : language === "hi" ? "languageHindi" : "languageMarathi");
}
